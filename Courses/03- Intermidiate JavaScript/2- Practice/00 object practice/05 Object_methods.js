// Iterating through object using key (object.keys)

let dog = {name: "Fido", age: 4};
console.log(Object.keys(dog)); // ==> print out the name of all keys in dog object

// Iterating through keys using values (object.values)
console.log(Object.values(dog)); // ==> print out the value of all keys in dog object

// Iterating through on object's keys and values (object.entries)
console.log(Object.entries(dog)); // prints out the keys with it's value
